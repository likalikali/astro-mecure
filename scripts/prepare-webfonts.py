"""Generate committed web fonts; not required during normal site builds.

Run with fonttools and brotli installed, passing --chinese and --google-dir.
The source fonts remain outside the repository.
"""
import argparse
from concurrent.futures import ProcessPoolExecutor
from hashlib import sha256
from io import BytesIO
import json
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'public' / 'fonts'


def unicode_ranges(points):
    spans = []
    for point in sorted(points):
        if spans and point == spans[-1][1] + 1:
            spans[-1][1] = point
        else:
            spans.append([point, point])
    return ','.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in spans)


def convert(job):
    source, name, family, weight, style, points = job
    font = TTFont(source, recalcTimestamp=False)
    if points is not None:
        options = subset.Options()
        options.name_IDs = ['*']
        options.name_languages = ['*']
        options.name_legacy = True
        worker = subset.Subsetter(options=options)
        worker.populate(unicodes=points)
        worker.subset(font)
    font.flavor = 'woff2'
    buffer = BytesIO()
    font.save(buffer)
    content = buffer.getvalue()
    filename = f'{name}.{sha256(content).hexdigest()[:10]}.woff2'
    (OUTPUT / filename).write_bytes(content)
    rule = (f'@font-face {{\n  font-family: "{family}";\n'
            f'  src: url("/fonts/{filename}") format("woff2");\n'
            f'  font-weight: {weight};\n  font-style: {style};\n  font-display: swap;\n')
    if points is not None:
        rule += f'  unicode-range: {unicode_ranges(points)};\n'
    return name, filename, rule + '}\n', len(content)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--chinese', required=True)
    parser.add_argument('--google-dir', required=True)
    args = parser.parse_args()
    OUTPUT.mkdir(parents=True, exist_ok=True)
    source = TTFont(args.chinese)
    available = set(source.getBestCmap())
    common = set(range(0x3000, 0x3100))
    for path in (ROOT / 'src').rglob('*'):
        if path.suffix in {'.astro', '.tsx', '.ts', '.md', '.mdx', '.json'}:
            common.update(ord(c) for c in path.read_text(encoding='utf-8') if ord(c) > 0x2FF)
    common.update(map(ord, '团子のUtopia'))
    common &= available
    remaining = sorted(available - common)
    groups = [('common', sorted(common))] + [
        (f'{i // 512:03}', remaining[i:i + 512]) for i in range(0, len(remaining), 512)
    ]
    jobs = [(args.chinese, f'kinghwa-oldsong-{name}', 'KingHwa OldSong', 400, 'normal', points)
            for name, points in groups]
    for face, weight, style in [('Regular', 400, 'normal'), ('Medium', 500, 'normal'),
                                ('Bold', 700, 'normal'), ('Italic', 400, 'italic'),
                                ('MediumItalic', 500, 'italic'), ('BoldItalic', 700, 'italic')]:
        jobs.append((str(Path(args.google_dir) / f'GoogleSans-{face}.ttf'),
                     f'google-sans-{face.lower()}', 'Google Sans', weight, style, None))
    with ProcessPoolExecutor(max_workers=4) as executor:
        results = list(executor.map(convert, jobs))
    css = '/* Generated by scripts/prepare-webfonts.py. All source glyphs are retained across subsets. */\n\n'
    css += '\n'.join(row[2] for row in results)
    (ROOT / 'src/styles/fonts.css').write_text(css, encoding='utf-8', newline='\n')
    manifest = {name: f'/fonts/{filename}' for name, filename, _, _ in results
                if name in {'kinghwa-oldsong-common', 'google-sans-regular'}}
    (ROOT / 'src/styles/fonts-manifest.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8', newline='\n')
    print(json.dumps({'fontFiles': len(results), 'chineseGlyphs': len(available),
                      'commonGlyphs': len(common), 'totalBytes': sum(row[3] for row in results),
                      'commonBytes': results[0][3]}, indent=2))


if __name__ == '__main__':
    main()
